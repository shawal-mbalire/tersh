#!/usr/bin/env python3
"""Regenerate the dependency inventory in THIRD-PARTY.txt.

Lists every Rust crate and npm package that ships in tersh (normal, not dev or
build-only, dependencies), with its version, license and home page, between
the BEGIN/END INVENTORY markers. Everything above the markers is written by
hand. Run with `just third-party`; `just third-party-check` fails if the file
is out of date.

Needs `cargo`, pnpm (or `$PNPM`) and an installed `frontend/node_modules`
(`just setup`).
"""

import json
import os
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
BACKEND = REPO / "backend"
FRONTEND = REPO / "frontend"
NOTICE = REPO / "THIRD-PARTY.txt"
BEGIN = "----- BEGIN INVENTORY (generated by `just third-party`; do not edit) -----"
END = "----- END INVENTORY -----"


def rust_crates():
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked"],
            cwd=BACKEND,
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])
    # Walk normal (non-dev, non-build) dependencies from the workspace crates.
    seen, stack = set(), list(members)
    while stack:
        node = nodes[stack.pop()]
        for dep in node["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                stack.append(dep["pkg"])
    rows = []
    for pid in seen - members:
        p = packages[pid]
        home = p.get("repository") or p.get("homepage") or f"https://crates.io/crates/{p['name']}"
        rows.append((p["name"], p["version"], p.get("license") or p.get("license_file") or "see crate", home))
    return sorted(set(rows))


def npm_packages():
    # pnpm, or whatever $PNPM names (as in the justfile), lists the shipped tree.
    pnpm = os.environ.get("PNPM", "pnpm").split()
    projects = json.loads(
        subprocess.run(
            [*pnpm, "ls", "--prod", "--depth", "Infinity", "--json"],
            cwd=FRONTEND,
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )
    rows, stack = set(), [item for project in projects for item in (project.get("dependencies") or {}).items()]
    while stack:
        name, info = stack.pop()
        manifest_path = Path(info.get("path", "")) / "package.json"
        if not info.get("path") or not manifest_path.exists():
            continue  # an optional peer that isn't installed (e.g. zone.js: the app is zoneless)
        manifest = json.loads(manifest_path.read_text())
        license = manifest.get("license") or "see package"
        if isinstance(license, dict):
            license = license.get("type", "see package")
        repo = manifest.get("repository") or {}
        home = repo.get("url") if isinstance(repo, dict) else repo
        home = (home or manifest.get("homepage") or f"https://www.npmjs.com/package/{name}").removeprefix("git+")
        rows.add((name, info.get("version", manifest.get("version", "?")), license, home))
        stack.extend((info.get("dependencies") or {}).items())
    return sorted(rows)


def table(rows):
    width_name = max(len(f"{n} {v}") for n, v, _, _ in rows)
    width_license = max(len(lic) for _, _, lic, _ in rows)
    return "\n".join(f"{f'{n} {v}':<{width_name}}  {lic:<{width_license}}  {home}" for n, v, lic, home in rows)


def inventory():
    crates, packages = rust_crates(), npm_packages()
    return "\n".join(
        [
            BEGIN,
            "",
            f"Rust crates ({len(crates)}), from backend/Cargo.lock:",
            "",
            table(crates),
            "",
            f"npm packages ({len(packages)}), from frontend/pnpm-lock.yaml:",
            "",
            table(packages),
            "",
            END,
        ]
    )


def main():
    text = NOTICE.read_text()
    head, _, rest = text.partition(BEGIN)
    _, _, tail = rest.partition(END)
    updated = head + inventory() + tail
    if "--check" in sys.argv:
        if updated != text:
            sys.exit("THIRD-PARTY.txt is out of date: run `just third-party`")
        return
    NOTICE.write_text(updated)


if __name__ == "__main__":
    main()
